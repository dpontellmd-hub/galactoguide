// Disposable Postgres only. No live accounts or email.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
const require = createRequire(path.resolve('.tmp/report-test-runtime/package.json'));
const { PGlite } = require('@electric-sql/pglite');
const db = new PGlite();
const old = '00000000-0000-4000-8000-000000000001';
const fresh = '00000000-0000-4000-8000-000000000002';
const other = '00000000-0000-4000-8000-000000000003';
const claims = async (id, email, amr = [], extras = {}) => {
  await db.query("select set_config('request.jwt.claims', $1, false)", [JSON.stringify({ sub: id, email, amr, ...extras })]);
};
const status = async () => (await db.query('select public.email_verification_status() as verified')).rows[0].verified;
const method = name => [{ method: name, timestamp: Math.floor(Date.now() / 1000) + 1 }];
try {
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create table auth.users(id uuid primary key, email text, created_at timestamptz default now(), email_confirmed_at timestamptz);
    create table auth.identities(user_id uuid, provider text, identity_data jsonb);
    create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb $$;
    create function auth.uid() returns uuid language sql stable as $$ select (auth.jwt()->>'sub')::uuid $$;
    grant usage on schema auth to authenticated, anon;
    insert into auth.users(id,email,email_confirmed_at) values('${old}', 'old@example.test', now());`);
  await db.exec(readFileSync('supabase/migrations/20260923_email_verification.sql', 'utf8'));
  await db.query('insert into auth.users(id,email,email_confirmed_at) values($1,$2,now()),($3,$4,now())', [fresh, 'new@example.test', other, 'other@example.test']);
  await db.exec('set role authenticated');
  await claims(old, 'old@example.test');
  assert.equal(await status(), true, 'Existing verified account preserved');
  await claims(fresh, 'new@example.test', method('password'), { user_metadata: { email_verified: true } });
  assert.equal(await status(), false, 'Auto confirmation and editable metadata cannot verify');
  await assert.rejects(db.exec(`update public.email_verifications set verified_at=now()`), /permission denied/);
  await assert.rejects(db.exec(`select * from public.email_verifications`), /permission denied/);
  await claims(fresh, 'new@example.test', method('otp'));
  assert.equal(await status(), false, 'SMS OTP does not prove email');
  await claims(fresh, 'new@example.test', method('email/signup'));
  assert.equal(await status(), false, 'Auto-confirmed signup does not prove email');
  await claims(fresh, 'wrong@example.test', method('magiclink'));
  assert.equal(await status(), false, 'Evidence must match the current address');
  await claims(fresh, 'new@example.test', [{ method: 'magiclink', timestamp: 1 }]);
  assert.equal(await status(), false, 'Old evidence rejected');
  await claims(fresh, 'new@example.test', method('magiclink'));
  assert.equal(await status(), true, 'Signed magic-link evidence accepted');
  await claims(other, 'other@example.test', method('password'));
  assert.equal(await status(), false, 'No cross-account verification');
  await db.exec('reset role');
  await db.query('update auth.users set email=$1 where id=$2', ['changed@example.test', fresh]);
  await db.exec('set role authenticated');
  await claims(fresh, 'new@example.test', method('magiclink'));
  assert.equal(await status(), false, 'Old-address session cannot verify changed email');
  await claims(fresh, 'changed@example.test', method('recovery'));
  assert.equal(await status(), true, 'Email recovery proves ownership');
  await db.exec('reset role');
  await db.query('insert into auth.identities values($1,$2,$3)', [other, 'google', JSON.stringify({ email: 'other@example.test', email_verified: true })]);
  await db.exec('set role authenticated');
  await claims(other, 'other@example.test', method('oauth'));
  assert.equal(await status(), true, 'Trusted Google identity accepted');
  await db.exec('set role anon');
  await assert.rejects(status(), /permission denied/);
  console.log('PASS: verification ownership, backfill, permissions, email changes, trusted evidence, and account isolation');
} finally { await db.close(); }
