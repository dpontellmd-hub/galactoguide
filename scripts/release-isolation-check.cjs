const assert = require('node:assert/strict');
const config = require('../app.config.js');
const app = require('../app.json').expo;
const vercel = require('../vercel.json');
assert.equal(vercel.git.deploymentEnabled['codex/release-readiness'], false);
delete process.env.EXPO_PUBLIC_SUPABASE_URL;
delete process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY;
delete process.env.GALACTOGUIDE_APPLE_SIGN_IN;
process.env.GALACTOGUIDE_ISOLATED_QA = '1';
const isolated = config({ config: app });
assert.equal(isolated.extra.supabaseUrl, 'https://release-fixture.invalid');
assert.equal(isolated.extra.supabaseAnonKey, 'public-isolated-fixture');
assert.equal(isolated.extra.appleSignInEnabled, false);
assert.equal(isolated.ios.usesAppleSignIn, undefined);
assert.equal(isolated.plugins.includes('expo-apple-authentication'), false);
process.env.EXPO_PUBLIC_SUPABASE_URL = app.extra.supabaseUrl;
assert.throws(() => config({ config: app }), /overrides to be unset/);
delete process.env.EXPO_PUBLIC_SUPABASE_URL;
delete process.env.GALACTOGUIDE_ISOLATED_QA;
assert.equal(config({ config: app }).extra.supabaseUrl, app.extra.supabaseUrl);
process.env.GALACTOGUIDE_APPLE_SIGN_IN = '1';
assert.throws(() => config({ config: app }), /isolated native backend/);
process.env.GALACTOGUIDE_NATIVE_BUILD = '1';
assert.throws(() => config({ config: app }), /isolated native backend/);
process.env.GALACTOGUIDE_ISOLATED_QA = '1';
const apple = config({ config: app });
assert.equal(apple.ios.usesAppleSignIn, true);
assert.equal(apple.extra.appleSignInEnabled, true);
assert.equal(apple.plugins.filter(p => p === 'expo-apple-authentication').length, 1);
delete process.env.GALACTOGUIDE_ISOLATED_QA;
process.env.EXPO_PUBLIC_SUPABASE_URL = 'https://aaaaaaaaaaaaaaaaaaaa.supabase.co';
process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY = 'sb_publishable_fixture';
assert.throws(() => config({ config: app }), /isolated native backend/);
process.env.GALACTOGUIDE_APPLE_ISOLATED_BACKEND = process.env.EXPO_PUBLIC_SUPABASE_URL;
assert.equal(config({ config: app }).extra.supabaseUrl, process.env.EXPO_PUBLIC_SUPABASE_URL);
assert.equal(config({ config: app }).extra.supabaseAnonKey, 'sb_publishable_fixture');
process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY = 'sb_secret_never_bundle';
assert.throws(() => config({ config: app }), /isolated native backend/);
delete process.env.EXPO_PUBLIC_SUPABASE_URL;
delete process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY;
delete process.env.GALACTOGUIDE_APPLE_ISOLATED_BACKEND;
delete process.env.GALACTOGUIDE_APPLE_SIGN_IN;
delete process.env.GALACTOGUIDE_NATIVE_BUILD;
console.log('PASS: default Apple off; isolated opt-in generates config; production/mismatched/secret-key settings refused; QA and draft deployment isolation preserved.');
