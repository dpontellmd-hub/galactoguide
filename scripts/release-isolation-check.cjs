const assert = require('node:assert/strict');
const config = require('../app.config.js');
const app = require('../app.json').expo;
const vercel = require('../vercel.json');
assert.equal(vercel.git.deploymentEnabled['codex/release-readiness'], false);
delete process.env.EXPO_PUBLIC_SUPABASE_URL;
delete process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY;
delete process.env.GALACTOGUIDE_APPLE_SIGN_IN;
process.env.GALACTOGUIDE_ISOLATED_QA = '1';
const isolated = config({ config: app });
assert.equal(isolated.extra.supabaseUrl, 'https://release-fixture.invalid');
assert.equal(isolated.extra.supabaseAnonKey, 'public-isolated-fixture');
assert.equal(isolated.extra.appleSignInEnabled, false);
assert.equal(isolated.ios.usesAppleSignIn, undefined);
assert.equal(isolated.plugins.includes('expo-apple-authentication'), false);
process.env.EXPO_PUBLIC_SUPABASE_URL = app.extra.supabaseUrl;
assert.throws(() => config({ config: app }), /overrides to be unset/);
delete process.env.EXPO_PUBLIC_SUPABASE_URL;
delete process.env.GALACTOGUIDE_ISOLATED_QA;
assert.equal(config({ config: app }).extra.supabaseUrl, app.extra.supabaseUrl);
console.log('PASS: isolated QA replaces live configuration, rejects conflicting overrides, Apple capability remains disabled, draft branch deployment is disabled.');
